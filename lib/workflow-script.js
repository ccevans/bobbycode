// lib/workflow-script.js
//
// Generates saved Claude Code Workflow scripts (.claude/workflows/bobby-<name>.js)
// from Bobby workflows, and prints the call that runs them. The stage loop
// (retry cap, debug on the 2nd rejection, iteration cap) lives in
// templates/workflows/runtime.js as code, not as prose for a model to follow.
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { resolveWorkflow, listWorkflows, nextStageName } from './workflow.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const RUNTIME_PATH = path.join(__dirname, '..', 'templates', 'workflows', 'runtime.js');
const WORKFLOWS_DIR = '.claude/workflows';
const NAME_PATTERN = /^[a-z0-9][a-z0-9-]*$/i;

export const ORCHESTRATION_MODES = ['prompt', 'workflow'];

/**
 * The orchestration mode in .bobbyrc.yml. Unset means 'prompt' (today's
 * behaviour). Anything else unknown, or 'workflow' on a target that has no
 * Workflow tool, is an error — never a quiet downgrade.
 */
export function resolveOrchestration(config = {}) {
  const value = config.orchestration;
  if (value === undefined || value === null) return 'prompt';
  if (!ORCHESTRATION_MODES.includes(value)) {
    throw new Error(`Unknown orchestration '${value}' in .bobbyrc.yml. Valid: ${ORCHESTRATION_MODES.join(', ')}`);
  }
  const target = config.target || 'claude-code';
  if (value === 'workflow' && target !== 'claude-code') {
    throw new Error(`orchestration: workflow needs target claude-code (target: ${target}). Claude Code's Workflow tool runs the scripts; other targets keep the prompt.`);
  }
  return value;
}

/**
 * The text of one saved script: a pure-literal `meta`, the baked steps, then
 * the shared runtime. Deterministic — same input, same bytes.
 */
export function buildWorkflowScript(name, steps) {
  if (!NAME_PATTERN.test(name)) {
    throw new Error(`Workflow name '${name}' can't be a script filename; use letters, digits and dashes`);
  }
  const baked = steps.map(s => ({ stage: s.stage, agent: s.agent, next: nextStageName(s.stage, steps) }));
  const terminal = baked.length > 0 ? baked[baked.length - 1].next : 'shipping';
  const execSteps = baked.filter(s => s.stage !== 'planning');
  const planStep = { stage: 'planning', agent: 'bobby-plan', next: execSteps.length > 0 ? execSteps[0].stage : terminal };

  const meta = {
    name: `bobby-${name}`,
    description: `Bobby "${name}" workflow (${steps.map(s => s.agent).join(' → ')}): code-enforced stage loop, retry cap, debug on 2nd rejection`,
    whenToUse: 'Printed by `bobby run workflow|feature|<name>` and `bobby sprint run` when .bobbyrc.yml has orchestration: workflow',
    phases: [{ title: 'Plan' }, { title: 'Execute' }, { title: 'Finalize' }],
  };
  const runtime = fs.readFileSync(RUNTIME_PATH, 'utf8');

  return [
    `export const meta = ${JSON.stringify(meta, null, 2)};`,
    '',
    `// Generated by bobby from workflow "${name}". Do not edit — \`bobby init --refresh\` rewrites it.`,
    `const WORKFLOW_NAME = ${JSON.stringify(name)};`,
    `const STEPS = ${JSON.stringify(baked)};`,
    `const EXEC_STEPS = ${JSON.stringify(execSteps)};`,
    `const PLAN_STEP = ${JSON.stringify(planStep)};`,
    `const TERMINAL = ${JSON.stringify(terminal)};`,
    '',
    runtime,
  ].join('\n');
}

function scriptRel(name) {
  return `${WORKFLOWS_DIR}/bobby-${name}.js`;
}

/**
 * Write one script per workflow when orchestration is 'workflow'; remove every
 * stale bobby-*.js otherwise. Files without the bobby- prefix are never touched.
 */
export function writeWorkflowScripts(rootDir, config = {}) {
  const mode = resolveOrchestration(config);
  const names = mode === 'workflow' ? listWorkflows(config) : [];

  // Build everything first so a bad workflow writes nothing.
  const scripts = names.map(name => [name, buildWorkflowScript(name, resolveWorkflow(config, name))]);

  const dir = path.join(rootDir, WORKFLOWS_DIR);
  const written = [];
  if (scripts.length > 0) {
    fs.mkdirSync(dir, { recursive: true });
    for (const [name, source] of scripts) {
      fs.writeFileSync(path.join(rootDir, scriptRel(name)), source, 'utf8');
      written.push(scriptRel(name));
    }
  }

  const pruned = [];
  if (fs.existsSync(dir)) {
    for (const file of fs.readdirSync(dir)) {
      const rel = `${WORKFLOWS_DIR}/${file}`;
      if (file.startsWith('bobby-') && file.endsWith('.js') && !written.includes(rel)) {
        fs.unlinkSync(path.join(dir, file));
        pruned.push(rel);
      }
    }
  }
  return { written, pruned };
}

/**
 * The saved script must exist and match what .bobbyrc.yml would generate now.
 * A missing or stale script is an error that names the fix.
 */
export function assertWorkflowScriptCurrent(rootDir, config, name) {
  const rel = scriptRel(name);
  const file = path.join(rootDir, rel);
  if (!fs.existsSync(file)) {
    throw new Error(`Saved workflow ${rel} not found. Run \`bobby init --refresh\` to generate it (orchestration: workflow).`);
  }
  const expected = buildWorkflowScript(name, resolveWorkflow(config, name));
  if (fs.readFileSync(file, 'utf8') !== expected) {
    throw new Error(`Saved workflow ${rel} is out of date with .bobbyrc.yml. Run \`bobby init --refresh\`.`);
  }
}

/** A ticket's frontmatter reduced to what the script's preflight needs. */
export function ticketSnapshot(data) {
  return {
    id: data.id,
    stage: data.stage || 'backlog',
    blocked: data.blocked === true,
    blockedReason: data.blocked_reason || null,
  };
}

/**
 * The `args` object for the Workflow tool. Default iteration caps match the
 * prose prompts exactly.
 */
export function buildWorkflowArgs({
  mode, tickets, workflow, maxRetries = 3, maxIterations,
  readFirst = [], planReadFirst = [], finalize = null, commands = {}, hasServices = false,
}) {
  let cap = maxIterations;
  if (!cap) {
    if (mode === 'feature') cap = tickets.length * workflow.length * 2;
    else if (mode === 'sprint') cap = Math.max(tickets.length * workflow.length * 2, 10);
    else cap = 20;
  }
  return {
    mode,
    tickets: tickets.map(t => ({ id: t.id, stage: t.stage, blocked: t.blocked === true, blockedReason: t.blockedReason || null })),
    maxRetries,
    maxIterations: cap,
    readFirst,
    planReadFirst,
    finalize,
    commands: { test: commands.test || null, lint: commands.lint || null },
    hasServices,
  };
}

/** The text `bobby run workflow|feature` and `sprint run` print instead of the prose prompt. */
export function formatWorkflowInvocation({ name, args, branchGuard }) {
  return `Run this as the saved Claude Code workflow **bobby-${name}** (orchestration: workflow).

0. Branch guard: ${branchGuard}
1. Call the Workflow tool with name \`bobby-${name}\` and exactly these args (a JSON object, not a string):
\`\`\`json
${JSON.stringify(args, null, 2)}
\`\`\`
2. If the run is interrupted, resume it in this same Claude Code session (a new session cannot see the cache and re-runs every agent): Workflow tool with scriptPath \`${scriptRel(name)}\`, resumeFromRunId = the runId from step 1, and the SAME args. Completed agents return from cache.
3. When it returns, report each ticket's status from the result. Do not re-run stages yourself.`;
}
